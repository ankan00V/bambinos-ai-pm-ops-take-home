def is_missing(value):
    return str(value).strip() in {"", "NULL", "null", "None", "NA"}


def column_profile(rows, column):
    values = [row.get(column, "") for row in rows]
    missing = sum(1 for value in values if is_missing(value))
    distinct = len({value for value in values if not is_missing(value)})
    numeric = [to_float(value) for value in values if not is_missing(value)]
    numeric_ok = bool(numeric) and all(is_missing(value) or _looks_numeric(value) for value in values)
    return {
        "column": column,
        "missing": missing,
        "missing_pct": round(100.0 * missing / len(rows), 1) if rows else 0.0,
        "distinct": distinct,
        "numeric": numeric_ok,
        "min": round(min(numeric), 2) if numeric and numeric_ok else None,
        "max": round(max(numeric), 2) if numeric and numeric_ok else None,
        "top": Counter(value for value in values if not is_missing(value)).most_common(5),
    }


def _looks_numeric(value):
    try:
        float(str(value).replace(",", ""))
        return True
    except ValueError:
        return False


def duplicate_rows(rows):
    seen = Counter(tuple(sorted(row.items())) for row in rows)
    return sum(count - 1 for count in seen.values() if count > 1)


def profile_file(path, table, key):
    rows = read_rows(path)
    keys = Counter(row.get(key, "") for row in rows)
    return {
        "table": table,
        "file": path.name,
        "rows": len(rows),
        "columns": len(rows[0]) if rows else 0,
        "key": key,
        "duplicate_keys": sum(count - 1 for count in keys.values() if count > 1),
        "duplicate_rows": duplicate_rows(rows),
        "blank_cells": sum(1 for row in rows for value in row.values() if is_missing(value)),
        "profiles": [column_profile(rows, column) for column in (rows[0].keys() if rows else [])],
    }


def join_report(dataset):
    methods = Counter()
    scores = []
    for form in dataset.forms:
        match = resolve_invoice(form, dataset.invoices_by_id, dataset.invoices)
        methods[match["method"]] += 1
        if match["method"] == "fuzzy":
            scores.append(round(match["score"], 3))
    invoice_ids = {str(row.get("id")) for row in dataset.invoices}
    booking_invoices = {str(row.get("invoice_id")) for row in dataset.bookings}
    schedule_invoices = {str(row.get("invoice_id")) for row in dataset.schedule}
    form_invoices = {str(row.get("invoice_id")) for row in dataset.forms}
    return {
        "form_to_invoice": dict(methods),
        "fuzzy_scores": scores,
        "invoice_ids": len(invoice_ids),
        "bookings_with_unknown_invoice": len(booking_invoices - invoice_ids),
        "schedule_with_unknown_invoice": len(schedule_invoices - invoice_ids),
        "forms_with_unknown_invoice_id": len(form_invoices - invoice_ids),
        "bookings_without_form": len({str(row.get("faculty_form_id")) for row in dataset.bookings} - {str(row.get("id")) for row in dataset.forms}),
        "schedule_without_booking": len({str(row.get("bookingrequest_id")) for row in dataset.schedule} - {str(row.get("id")) for row in dataset.bookings}),
        "reference_students": len(dataset.reference_by_student),
        "invoice_students_missing_from_reference": len({str(row.get("student_id")) for row in dataset.invoices} - set(dataset.reference_by_student)),
        "form_students_missing_from_reference": len({str(row.get("student_id")) for row in dataset.forms} - set(dataset.reference_by_student)),
    }


def render(profiles, joins):
    lines = []
    lines.append("# Data profile")
    lines.append("")
    lines.append("Generated by engine/profile.py from the five CSVs in data/. Every number below is counted, not estimated.")
    lines.append("")
    lines.append("## Table summary")
    lines.append("")
    lines.append("| Table | Rows | Columns | Duplicate keys | Duplicate rows | Blank cells |")
    lines.append("| --- | --- | --- | --- | --- | --- |")
    for item in profiles:
        lines.append(
            "| {} | {} | {} | {} | {} | {} |".format(
                item["table"], item["rows"], item["columns"], item["duplicate_keys"], item["duplicate_rows"], item["blank_cells"]
            )
        )
    lines.append("")
    for item in profiles:
        lines.append("## {}".format(item["table"]))
        lines.append("")
        lines.append("File `{}`, {} rows, key `{}`.".format(item["file"], item["rows"], item["key"]))
        lines.append("")
        lines.append("| Column | Missing | Missing % | Distinct | Min | Max | Top values |")
        lines.append("| --- | --- | --- | --- | --- | --- | --- |")
        for column in item["profiles"]:
            top = ", ".join("{} ({})".format(value, count) for value, count in column["top"][:3])
            lines.append(
                "| {} | {} | {} | {} | {} | {} | {} |".format(
                    column["column"],
                    column["missing"],
                    column["missing_pct"],
                    column["distinct"],
                    "" if column["min"] is None else column["min"],
                    "" if column["max"] is None else column["max"],
                    top.replace("|", "/"),
                )
            )
        lines.append("")
    lines.append("## Join reliability")
    lines.append("")
    lines.append("| Check | Value |")
    lines.append("| --- | --- |")
    for key, value in joins.items():
        lines.append("| {} | {} |".format(key, value))
    lines.append("")
    lines.append("Form to invoice resolution counts show how each form was linked. Exact means the form invoice_id exists, link means only the URL resolved, fuzzy means a typo was repaired, none or ambiguous means it was rejected.")
    lines.append("")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description="Profile the five renewal CSVs.")
    parser.add_argument("--data-dir", default=None)
    parser.add_argument("--out", default=str(ROOT / "docs" / "data_profile.md"))
    parser.add_argument("--quiet", action="store_true")
    args = parser.parse_args()

    base = Path(args.data_dir) if args.data_dir else config.DATA_DIR
    profiles = [profile_file(base / name, table, key) for name, table, key in FILES]
    joins = join_report(load_dataset(base))
    document = render(profiles, joins)

    target = Path(args.out)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(document, encoding="utf-8")

    if not args.quiet:
        print(document)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
